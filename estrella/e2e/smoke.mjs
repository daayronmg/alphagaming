import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = process.env.BASE || 'http://localhost:5173';
const OUT = process.env.OUT || '.';
const b = await chromium.launch();
const login = async (email, viewport) => {
  const ctx = await b.newContext({ viewport });
  const p = await ctx.newPage();
  p.on('console', (m) => { if (m.type() === 'error') console.log(`[${email}] console:`, m.text()); });
  p.on('pageerror', (e) => console.log(`[${email}] pageerror:`, e.message));
  await p.goto(`${BASE}/login`);
  await p.fill('input[name=usuario]', email);
  await p.fill('input[type=password]', 'Estrella2026demo');
  await p.click('button:has-text("Entrar")');
  await p.waitForURL((u) => !u.pathname.startsWith('/login'));
  return p;
};
const emilio = await login('emilio@estrella.demo', { width: 1280, height: 900 });
await emilio.waitForTimeout(800);
await emilio.screenshot({ path: `${OUT}/01-home-director.png` });
const a = await login('componente.a@estrella.demo', { width: 400, height: 860 });
await a.screenshot({ path: `${OUT}/02-home-a.png` });
await emilio.goto(`${BASE}/biblioteca`);
await emilio.waitForTimeout(800);
await emilio.screenshot({ path: `${OUT}/03-library.png` });
await emilio.click('text=Marcha de demostración (ESTRELLA)');
await emilio.waitForTimeout(800);
await emilio.screenshot({ path: `${OUT}/04-marcha.png`, fullPage: true });
await emilio.click('[data-testid=open-my-part], text=Abrir').catch(() => {});
await b.close();
