import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 860 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto('http://localhost:5173/login');
await p.fill('input[name=usuario]', 'emilio@estrella.demo'); await p.fill('input[type=password]', 'Estrella2026demo');
await p.click('button:has-text("Entrar")'); await p.waitForURL((u) => !u.pathname.startsWith('/login'));
const api = (path, method = 'GET', body) => p.evaluate(async ({ path, method, body }) => (await (await fetch('/api' + path, { method, headers: { 'x-estrella': '1', 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined })).json()), { path, method, body });
for (const l of await api('/live/active')) await api(`/live/${l.id}/end`, 'POST', {});
const m = (await api('/library/marchas?q=demostraci')).find((x) => x.title.includes('(ESTRELLA)'));
const d = await api('/library/marchas/' + m.id);
const part = d.parts.find((x) => x.label === 'Corneta 3ª voz');
const s = await api('/live', 'POST', {});
await api(`/live/${s.id}/cmd`, 'POST', { type: 'select_marcha', marchaId: m.id });
await p.goto('http://localhost:5173/direccion/' + s.id);
await p.waitForTimeout(1500);
const sel = p.locator('select:near(:text("Partitura en la tableta:"))');
console.log('select count', await sel.count());
await sel.first().selectOption(part.id);
const ws = p.locator(`[data-testid=part-workspace][data-part-id="${part.id}"]`);
await ws.waitFor();
await ws.locator('[data-testid=layer-select]').selectOption('official');
await ws.locator('[data-tool=pen]').click();
await ws.locator('.score-page svg.layer').first().evaluate((el) => el.scrollIntoView({ block: 'center' }));
await p.waitForTimeout(600);
const box = await ws.locator('.score-page svg.layer').first().boundingBox();
console.log('box', box);
const pt = { x: box.x + box.width * 0.3, y: Math.min(box.y + box.height * 0.2, 800) };
console.log('pt', pt, await p.evaluate(({ x, y }) => { const e = document.elementFromPoint(x, y); return e?.tagName + ' ' + (e?.getAttribute('class') || ''); }, pt));
await p.mouse.move(pt.x, pt.y); await p.mouse.down();
for (let i = 1; i <= 12; i++) await p.mouse.move(pt.x + i * 10, pt.y + (i % 2) * 5);
await p.mouse.up();
await p.waitForTimeout(800);
const anns = await api(`/annotations?marcha=${m.id}&part=${part.id}`);
console.log('anns', anns.annotations.map((a) => a.kind + ':' + a.layer));
await p.screenshot({ path: process.env.OUT + '/console-draw.png' });
await api(`/live/${s.id}/end`, 'POST', {});
await b.close();
