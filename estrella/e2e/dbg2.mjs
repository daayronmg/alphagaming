import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto('http://localhost:5173/login');
await p.fill('input[name=usuario]', 'emilio@estrella.demo'); await p.fill('input[type=password]', 'Estrella2026demo');
await p.click('button:has-text("Entrar")'); await p.waitForURL((u) => !u.pathname.startsWith('/login'));
const r = await p.evaluate(async () => (await (await fetch('/api/library/marchas?q=demostraci')).json()));
const m = r.find((x) => x.title.includes('(ESTRELLA)'));
const d = await p.evaluate(async (id) => (await (await fetch('/api/library/marchas/' + id)).json()), m.id);
const part = d.parts.find((x) => x.label === 'Corneta 3ª voz');
const s = d.scores.find((x) => x.label === 'Corneta 3ª voz');
await p.goto('http://localhost:5173/partitura/' + part.id);
await p.locator('.score-page canvas').first().waitFor();
await p.waitForTimeout(1000);
await p.locator('[data-testid=layer-select]').selectOption('official');
await p.locator('[data-tool=pen]').click();
const box = await p.locator('.score-page svg.layer').first().boundingBox();
console.log('box', box, 'pointer-events', await p.locator('.score-page svg.layer').first().evaluate((e) => getComputedStyle(e).pointerEvents));
const el = await p.evaluate(({ x, y }) => { const e = document.elementFromPoint(x, y); return e?.tagName + '.' + e?.className?.baseVal + '/' + e?.className; }, { x: box.x + box.width * 0.3, y: box.y + box.height * 0.2 });
console.log('element at point', el);
await p.mouse.move(box.x + box.width * 0.3, box.y + box.height * 0.2);
await p.mouse.down();
for (let i = 1; i <= 12; i++) await p.mouse.move(box.x + box.width * (0.3 + i * 0.02), box.y + box.height * (0.2 + (i % 2) * 0.01));
await p.mouse.up();
await p.waitForTimeout(800);
const anns = await p.evaluate(async ([mid, pid]) => (await (await fetch(`/api/annotations?marcha=${mid}&part=${pid}`)).json()), [m.id, part.id]);
console.log('anns', anns.annotations.map((a) => a.kind + ':' + a.layer));
await p.screenshot({ path: process.env.OUT + '/draw.png' });
await p.goto('http://localhost:5173/score/' + s.id);
await p.click('[data-testid=edit-score]');
await p.waitForTimeout(1500);
const ids = await p.evaluate(() => [...document.querySelectorAll('[data-testid=staff] .vf-stavenote')].slice(0, 3).map((e) => e.id + ' ' + e.getAttribute('class')));
console.log('vf ids', ids);
await b.close();
